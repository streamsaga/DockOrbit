/**
 * Simple keyword search across all mock channels (name + description),
 * used by the search bar in mock-data mode.
 */
export function searchMockChannels(query) {
  const q = query.toLowerCase();
  const all = Object.values(mockChannels).flat();
  return all.filter(
    (ch) =>
      ch.name.toLowerCase().includes(q) || ch.description.toLowerCase().includes(q)
  );
}